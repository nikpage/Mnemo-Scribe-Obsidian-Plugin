export type Lang = keyof typeof translations;

/**
 * The languages a user can pick as their primary one. Named in English
 * because the names are fed to the analysis model, not shown in the UI.
 */
export const LANGUAGE_NAMES = {
  en: "English",
  cs: "Czech",
} as const satisfies Record<keyof typeof translations, string>;
export type TranslationKey = keyof (typeof translations)["en"];

export function detectLang(): Lang {
  if (typeof navigator === "undefined") return "en";
  const lang = navigator.language.slice(0, 2);
  return lang === "cs" ? "cs" : "en";
}

/** Values for a string's `{name}` placeholders. */
export type Vars = Record<string, string | number>;

export function t(key: TranslationKey, lang: Lang, vars?: Vars): string {
  return fill(translations[lang][key] ?? translations.en[key] ?? key, lang, vars);
}

/** `{name}` in `text` filled from `vars`; `{n|one|few|other}` takes the count's word. */
export function fill(text: string, lang: Lang, vars?: Vars): string {
  return vars ? text.replace(/\{(\w+)((?:\|[^|}]*)*)\}/g, (all, name, forms) => {
    if (!(name in vars)) return all;
    if (!forms) return String(vars[name]);
    return `${vars[name]} ${countWord(lang, vars[name], forms.slice(1).split("|"))}`;
  }) : text;
}

/** The word a count takes: one|few|other in Czech (1, 2–4, 5+), one|other in English. */
function countWord(lang: Lang, n: string | number, forms: string[]): string {
  const kind = typeof n === "number" ? new Intl.PluralRules(lang).select(n) : "other";
  return kind === "one" ? forms[0] : kind === "few" ? forms[1] : forms[forms.length - 1];
}
